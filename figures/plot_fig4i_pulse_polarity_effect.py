# Helpers
# =============================================================================
def _find_first_existing_column(
    df: pd.DataFrame,
    candidates: list[str],
    metric_name: str,
) -> str:
    for col in candidates:
        if col in df.columns:
            return col

    raise RuntimeError(
        f"No column found for {metric_name}. "
        f"Expected one of: {candidates}\n"
        f"Available columns: {list(df.columns)}"
    )


def _find_row_by_part(
    df: pd.DataFrame,
    part: str,
) -> pd.Series:
    rows = df[
        df["part"]
        .astype(str)
        .str.lower()
        == part.lower()
    ].copy()

    if rows.empty:
        rows = df[
            df["config"]
            .astype(str)
            .str.lower()
            .str.contains(part.lower())
        ].copy()

    if rows.empty:
        raise RuntimeError(
            f"No row found for polarity part: {part}"
        )

    return rows.iloc[0]


def _to_percent_scale(values) -> np.ndarray:
    """Convert 0-1 scale to percentage points when needed."""
    arr = pd.to_numeric(values, errors="coerce").to_numpy(dtype=float)
    finite = arr[np.isfinite(arr)]

    if len(finite) > 0 and np.nanmax(np.abs(finite)) <= 1.5:
        arr = arr * 100.0

    return arr


def _load_full_pulse_result(path: str) -> dict:
    """
    Compute the full-pulse metrics directly from per-sample predictions.

    This avoids reusing the old manually entered MedAPE values after the
    manuscript metric has been changed to MedAE.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Full-pulse prediction CSV not found: {path}\n"
            "Please generate the proposed-framework per-sample predictions first."
        )

    pred = pd.read_csv(path)

    required = [
        "true_label",
        "pred_label",
        "soc_true",
        "soc_pred",
        "soh_true",
        "soh_pred",
    ]

    missing = [c for c in required if c not in pred.columns]
    if missing:
        raise RuntimeError(
            f"Missing required columns in full-pulse prediction CSV: {missing}"
        )

    true_material = (
        pred["true_label"]
        .astype(str)
        .str.split("_")
        .str[0]
    )

    pred_material = (
        pred["pred_label"]
        .astype(str)
        .str.split("_")
        .str[0]
    )

    material_acc = float(
        np.mean(
            true_material.to_numpy()
            == pred_material.to_numpy()
        )
    )

    soc_true = _to_percent_scale(pred["soc_true"])
    soc_pred = _to_percent_scale(pred["soc_pred"])
    soh_true = _to_percent_scale(pred["soh_true"])
    soh_pred = _to_percent_scale(pred["soh_pred"])

    soc_valid = np.isfinite(soc_true) & np.isfinite(soc_pred)
    soh_valid = np.isfinite(soh_true) & np.isfinite(soh_pred)

    if not np.any(soc_valid):
        raise RuntimeError("No valid SOC predictions found for full pulse.")
    if not np.any(soh_valid):
        raise RuntimeError("No valid SOH predictions found for full pulse.")

    soc_medae = float(
        np.median(
            np.abs(
                soc_pred[soc_valid]
                - soc_true[soc_valid]
            )
        )
    )

    soh_medae = float(
        np.median(
            np.abs(
                soh_pred[soh_valid]
                - soh_true[soh_valid]
            )
        )
    )

    return {
        "Method": "Full pulse",
        "Material accuracy": material_acc,
        "SOC MedAE (%)": soc_medae,
        "SOH MedAE (%)": soh_medae,
    }


