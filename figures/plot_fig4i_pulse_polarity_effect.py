# =============================================================================
# Helper functions for plotting
# =============================================================================
def fmt_value(
    v: float,
    metric: str,
) -> str:
    if metric == "Material accuracy":
        return f"{v * 100.0:.1f}%"

    return f"{v:.2f}%"


def gain_value(
    full_v: float,
    base_v: float,
    higher_better: bool = True,
) -> float:
    if (
        not np.isfinite(full_v)
        or not np.isfinite(base_v)
        or abs(base_v) < 1e-12
    ):
        return np.nan

    if higher_better:
        return (
            (full_v - base_v)
            / base_v
            * 100.0
        )

    return (
        (base_v - full_v)
        / base_v
        * 100.0
    )


# =============================================================================
# Plot configuration
# =============================================================================
metrics = [
    "Material accuracy",
    "SOC MedAE (%)",
    "SOH MedAE (%)",
]

titles = [
    "Material",
    "SOC",
    "SOH",
]

higher_is_better = {
    "Material accuracy": True,
    "SOC MedAE (%)": False,
    "SOH MedAE (%)": False,
}

colors = {
    "Positive only": "#4E79A7",
    "Negative only": "#F28E2B",
    "Full pulse": "#1B9E77",
}

markers = {
    "Positive only": "o",
    "Negative only": "s",
    "Full pulse": "D",
}


plt.rcParams.update(
    {
        "font.family": "Arial",
        "font.size": 8.5,
        "axes.linewidth": 0.85,
        "xtick.major.width": 0.75,
        "ytick.major.width": 0.75,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
    }
)


# =============================================================================
# Plot
# =============================================================================
fig, axes = plt.subplots(
    1,
    3,
    figsize=(7 * 5.84 / 5.61, 2.95),
    gridspec_kw={
        "wspace": 0.42,
    },
)


for ax, metric, title in zip(
    axes,
    metrics,
    titles,
):
    pos_v = df.loc[
        df["Method"] == "Positive only",
        metric,
    ].iloc[0]

    neg_v = df.loc[
        df["Method"] == "Negative only",
        metric,
    ].iloc[0]

    full_v = df.loc[
        df["Method"] == "Full pulse",
        metric,
    ].iloc[0]

    higher_better = higher_is_better[metric]

    y_single = 0.0
    y_full = 1.0

    vals = np.array(
        [
            pos_v,
            neg_v,
            full_v,
        ],
        dtype=float,
    )

    vals = vals[
        np.isfinite(vals)
    ]

    vmin = np.min(vals)
    vmax = np.max(vals)

    span = vmax - vmin

    pad = (
        span * 0.42
        if span > 0
        else max(
            abs(vmax) * 0.08,
            0.05,
        )
    )

    ax.set_xlim(
        vmin - pad,
        vmax + pad,
    )

    ax.set_ylim(
        -0.43,
        1.43,
    )

    # -------------------------------------------------------------------------
    # Background
    # -------------------------------------------------------------------------
    ax.axhspan(
        -0.25,
        0.25,
        color="#F2F2F2",
        alpha=1.0,
        zorder=0,
    )

    ax.axhspan(
        0.75,
        1.25,
        color=colors["Full pulse"],
        alpha=0.075,
        zorder=0,
    )

    # -------------------------------------------------------------------------
    # Dumbbell
    # -------------------------------------------------------------------------
    ax.plot(
        [
            pos_v,
            neg_v,
        ],
        [
            y_single,
            y_single,
        ],
        color="0.55",
        linewidth=6.0,
        alpha=0.22,
    )

    # -------------------------------------------------------------------------
    # Points
    # -------------------------------------------------------------------------
    ax.scatter(
        pos_v,
        y_single,
        s=70,
        color=colors["Positive only"],
        marker=markers["Positive only"],
        edgecolor="white",
        linewidth=0.9,
        zorder=3,
    )

    ax.scatter(
        neg_v,
        y_single,
        s=70,
        color=colors["Negative only"],
        marker=markers["Negative only"],
        edgecolor="white",
        linewidth=0.9,
        zorder=3,
    )

    ax.scatter(
        full_v,
        y_full,
        s=105,
        color=colors["Full pulse"],
        marker=markers["Full pulse"],
        edgecolor="white",
        linewidth=1.0,
        zorder=4,
    )

    # -------------------------------------------------------------------------
    # Arrows
    # -------------------------------------------------------------------------
    arrow_style = {
        "arrowstyle": "-|>",
        "lw": 1.55,
        "alpha": 0.80,
    }

    ax.annotate(
        "",
        xy=(
            full_v,
            y_full - 0.06,
        ),
        xytext=(
            pos_v,
            y_single + 0.08,
        ),
        arrowprops={
            **arrow_style,
            "color": colors["Positive only"],
        },
    )

    ax.annotate(
        "",
        xy=(
            full_v,
            y_full - 0.06,
        ),
        xytext=(
            neg_v,
            y_single + 0.08,
        ),
        arrowprops={
            **arrow_style,
            "color": colors["Negative only"],
        },
    )

    # -------------------------------------------------------------------------
    # Values
    # -------------------------------------------------------------------------
    ax.text(
        pos_v,
        y_single - 0.18,
        fmt_value(
            pos_v,
            metric,
        ),
        ha="center",
    )

    ax.text(
        neg_v,
        y_single + 0.17,
        fmt_value(
            neg_v,
            metric,
        ),
        ha="center",
    )

    ax.text(
        full_v,
        y_full + 0.17,
        fmt_value(
            full_v,
            metric,
        ),
        ha="center",
        fontweight="bold",
    )

    # -------------------------------------------------------------------------
    # Gains
    # -------------------------------------------------------------------------
    gain_pos = gain_value(
        full_v,
        pos_v,
        higher_better,
    )

    gain_neg = gain_value(
        full_v,
        neg_v,
        higher_better,
    )

    ax.text(
        0.98,
        0.5,
        (
            f"vs Pos {gain_pos:+.1f}%\n"
            f"vs Neg {gain_neg:+.1f}%"
        ),
        transform=ax.transAxes,
        ha="right",
        va="center",
        bbox={
            "facecolor": "white",
            "alpha": 0.9,
        },
    )

    # -------------------------------------------------------------------------
    # Axes
    # -------------------------------------------------------------------------
    ax.set_title(title)

    if metric == "Material accuracy":
        ax.set_xlabel("Material accuracy")
    else:
        ax.set_xlabel("MedAE (%)")

    ax.set_yticks(
        [
            y_single,
            y_full,
        ]
    )

    ax.set_yticklabels(
        [
            "Single\npolarity",
            "Full\npulse",
        ]
    )

    ax.grid(
        axis="x",
        linestyle="--",
        alpha=0.3,
    )

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


